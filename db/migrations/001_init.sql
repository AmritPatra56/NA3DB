-- T4-01  atom_site (LARGEST TABLE)
CREATE TABLE IF NOT EXISTS atom_site (
    id                 BIGINT      GENERATED BY DEFAULT AS IDENTITY,
    entry_id           VARCHAR(20) NOT NULL,
    group_PDB          VARCHAR(10),
    type_symbol        VARCHAR(5),
    label_atom_id      VARCHAR(20),
    label_alt_id       VARCHAR(5),
    label_comp_id      VARCHAR(10),
    label_asym_id      VARCHAR(20) NOT NULL,
    label_entity_id    VARCHAR(20),
    label_seq_id       INT,
    Cartn_x            REAL,
    Cartn_y            REAL,
    Cartn_z            REAL,
    occupancy          REAL,
    B_iso_or_equiv     REAL,
    auth_seq_id        VARCHAR(20),
    auth_asym_id       VARCHAR(10),
    auth_comp_id       VARCHAR(10),
    auth_atom_id       VARCHAR(20),
    pdbx_PDB_model_num INT,
    pdbx_formal_charge INT,
    pdbx_PDB_ins_code  VARCHAR(5),
    PRIMARY KEY (id),
    CONSTRAINT fk_as_asym
        FOREIGN KEY (label_asym_id, entry_id)
        REFERENCES struct_asym(id, entry_id) ON DELETE CASCADE
);
CREATE INDEX IF NOT EXISTS idx_as_entry ON atom_site (entry_id);
CREATE INDEX IF NOT EXISTS idx_as_chain ON atom_site (label_asym_id, entry_id);
CREATE INDEX IF NOT EXISTS idx_as_model ON atom_site (entry_id, pdbx_PDB_model_num);
COMMENT ON TABLE atom_site IS 'All atom coordinates. LARGEST TABLE.';


-- T4-02  atom_sites (fractional-to-Cartesian, 1:1 with entry)
CREATE TABLE IF NOT EXISTS atom_sites (
    entry_id                VARCHAR(20) NOT NULL,
    fract_transf_matrix_1_1 DOUBLE PRECISION,
    fract_transf_matrix_1_2 DOUBLE PRECISION,
    fract_transf_matrix_1_3 DOUBLE PRECISION,
    fract_transf_matrix_2_1 DOUBLE PRECISION,
    fract_transf_matrix_2_2 DOUBLE PRECISION,
    fract_transf_matrix_2_3 DOUBLE PRECISION,
    fract_transf_matrix_3_1 DOUBLE PRECISION,
    fract_transf_matrix_3_2 DOUBLE PRECISION,
    fract_transf_matrix_3_3 DOUBLE PRECISION,
    fract_transf_vector_1   DOUBLE PRECISION,
    fract_transf_vector_2   DOUBLE PRECISION,
    fract_transf_vector_3   DOUBLE PRECISION,
    PRIMARY KEY (entry_id),
    CONSTRAINT fk_ats_entry
        FOREIGN KEY (entry_id) REFERENCES entry(id) ON DELETE CASCADE
);
COMMENT ON TABLE atom_sites IS 'Fractional-to-Cartesian matrix. 1:1. CIF []->_ in column names.';


