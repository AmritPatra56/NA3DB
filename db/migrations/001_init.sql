-- PostgreSQL port of NADB schema (source: final_schema.sql, MySQL/InnoDB).
-- Run as superuser or owner:
--   createdb -E UTF8 nadb
--   psql -d nadb -f final_schema_postgres.sql
-- Note: PostgreSQL folds unquoted identifiers to lowercase.
-- Loaders must lowercase CIF keys (e.g. Cartn_x → cartn_x) before binding.

-- ============================================================
--  TIER 1 — ENTRY CORE
-- ============================================================

-- T1-01  entry  ── ABSOLUTE ROOT
CREATE TABLE IF NOT EXISTS entry (
    id  VARCHAR(20) NOT NULL,
    PRIMARY KEY (id)
);
COMMENT ON TABLE entry IS 'ROOT. One row per PDB entry. All other tables reference this.';


-- T1-02  pdbx_database_status  (1:1 with entry)
CREATE TABLE IF NOT EXISTS pdbx_database_status (
    entry_id                      VARCHAR(20) NOT NULL,
    status_code                   VARCHAR(10),
    recvd_initial_deposition_date DATE,
    deposit_site                  VARCHAR(20),
    process_site                  VARCHAR(20),
    status_code_sf                VARCHAR(10),
    pdb_format_compatible         VARCHAR(5),
    PRIMARY KEY (entry_id),
    CONSTRAINT fk_dbs_entry
        FOREIGN KEY (entry_id) REFERENCES entry(id) ON DELETE CASCADE
);


-- T1-03  struct  (1:1 with entry)
CREATE TABLE IF NOT EXISTS struct (
    entry_id VARCHAR(20) NOT NULL,
    title    TEXT,
    PRIMARY KEY (entry_id),
    CONSTRAINT fk_struct_entry
        FOREIGN KEY (entry_id) REFERENCES entry(id) ON DELETE CASCADE
);


-- T1-04  citation
CREATE TABLE IF NOT EXISTS citation (
    id                      VARCHAR(30) NOT NULL,
    entry_id                VARCHAR(20) NOT NULL,
    title                   TEXT,
    journal_abbrev          TEXT,
    journal_volume          VARCHAR(50),
    page_first              VARCHAR(20),
    page_last               VARCHAR(20),
    year                    SMALLINT,
    journal_id_ASTM         VARCHAR(20),
    country                 VARCHAR(10),
    journal_id_ISSN         VARCHAR(20),
    journal_id_CSD          VARCHAR(20),
    book_publisher          TEXT,
    pdbx_database_id_PubMed INT,
    pdbx_database_id_DOI    TEXT,
    PRIMARY KEY (id, entry_id),
    CONSTRAINT fk_cit_entry
        FOREIGN KEY (entry_id) REFERENCES entry(id) ON DELETE CASCADE
);
CREATE INDEX IF NOT EXISTS idx_cit_entry ON citation (entry_id);


-- T1-05  citation_author
CREATE TABLE IF NOT EXISTS citation_author (
    id               INTEGER     GENERATED BY DEFAULT AS IDENTITY,
    entry_id         VARCHAR(20) NOT NULL,
    citation_id      VARCHAR(30) NOT NULL,
    name             TEXT,
    ordinal          INT,
    identifier_ORCID TEXT,
    PRIMARY KEY (id),
    CONSTRAINT fk_ca_entry
        FOREIGN KEY (entry_id) REFERENCES entry(id) ON DELETE CASCADE,
    CONSTRAINT fk_ca_citation
        FOREIGN KEY (citation_id, entry_id)
        REFERENCES citation(id, entry_id) ON DELETE CASCADE
);
CREATE INDEX IF NOT EXISTS idx_ca_entry    ON citation_author (entry_id);
CREATE INDEX IF NOT EXISTS idx_ca_citation ON citation_author (citation_id, entry_id);


