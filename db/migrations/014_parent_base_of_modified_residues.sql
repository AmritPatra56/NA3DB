-- The parent base of each modified residue (5MC pairs as C, PSU as U), so a
-- Watson-Crick pair is recognised when one side is modified: 1OB5's G30-5MC40
-- is cWW_G-5MC in the annotation and is a G-C pair.
--
-- chem_comp is global and one code has one parent; the loader fills it from
-- pdbx_struct_mod_residue.parent_comp_id. The values below were read from that
-- category in the 238 of 1,489 files that have it (no code had two parents),
-- so the rows already loaded get it without a reload. Codes with no parent
-- there stay NULL and are judged on their own code.
ALTER TABLE chem_comp ADD COLUMN parent_comp_id varchar(10);

COMMENT ON COLUMN chem_comp.parent_comp_id IS
    'Standard residue this one is modified from (pdbx_struct_mod_residue.parent_comp_id). See db/migrations/014.';

